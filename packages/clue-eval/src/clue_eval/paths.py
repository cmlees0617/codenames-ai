"""Filesystem paths for packaged evaluation data."""

from __future__ import annotations

from pathlib import Path


def package_data_dir() -> Path:
    """Directory containing ``test_boards.json`` and other fixture data."""
    return Path(__file__).resolve().parents[2] / "data"


def default_test_boards_path() -> Path:
    return package_data_dir() / "test_boards.json"


def default_words_path() -> Path:
    return package_data_dir() / "words.txt"


def default_embeddings_path() -> Path:
    return package_data_dir() / "glove-wiki-gigaword-300.npz"


def default_standard_boards_path() -> Path:
    """Standard 5000-board benchmark set.

    Generated by ``examples/generate_standard_board_set.py``.
    """
    return package_data_dir() / "standard_boards_5000.json"
